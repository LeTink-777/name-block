export function getBlock(num: number): Block | null {
  return BLOCKS[num] ?? null;
}

export function pdfTitle(userData: UserData): string {
  const num = nameNumber(userData.name || '');
  const block = num ? getBlock(num) : null;
  return block ? `${block.name} — число ${num}` : SITE.name;
}

export function buildSections(userData: UserData, plan: PlanId): Section[] {
  const num = nameNumber(userData.name || '');
  const block = num ? getBlock(num) : null;

  if (!block || !num) {
    return [
      {
        title: 'Данные не распознаны',
        content:
          'Не удалось рассчитать число имени. Вернитесь на сайт и введите имя русскими буквами.',
      },
    ];
  }

  const sections: Section[] = [];

  sections.push({
    title: 'Число вашего имени',
    content: `Имя: ${userData.name}\nЧисло имени: ${num}${num === 11 || num === 22 ? ' (мастер-число)' : ''}\n\n${block.name}.`,
  });

  sections.push({ title: 'Ваш денежный блок', content: block.short });

  if (plan === 'basic' || plan === 'full' || plan === 'premium') {
    sections.push({ title: 'Как блок проявляется', content: block.manifestations });
  }

  if (plan === 'full' || plan === 'premium') {
    sections.push({ title: 'Корень блока', content: block.root });
    sections.push({ title: 'Три шага, чтобы убрать блок', content: block.steps });
    sections.push({ title: 'Аффирмация для перепрограммирования', content: block.affirmation });
    sections.push({ title: 'Что изменится, когда блок уйдёт', content: block.afterwards });
  }

  if (plan === 'premium') {
    sections.push({ title: '30-дневная программа снятия блока', content: block.program });
    sections.push({ title: 'Персональные аффирмации', content: block.personalAffirmations });
  }

  sections.push({
    title: 'О документе',
    content: `Тариф: ${PLAN_LABELS[plan]}. Материал носит развлекательный характер, не является финансовой или психологической консультацией. Нумерология — не наука; практическая ценность разбора в предложенных упражнениях.`,
  });

  return sections;
}
