/** Русская таблица Пифагора: буква → число. */
const LETTER_VALUES: Record<string, number> = {};
const ROWS: [number, string][] = [
  [1, 'АИСЪ'],
  [2, 'БЙТЫ'],
  [3, 'ВКУЬ'],
  [4, 'ГЛФЭ'],
  [5, 'ДМХЮ'],
  [6, 'ЕНЦЯ'],
  [7, 'ЁОЧ'],
  [8, 'ЖПШ'],
  [9, 'ЗРЩ'],
];
for (const [value, letters] of ROWS) {
  for (const letter of letters) LETTER_VALUES[letter] = value;
}

export function nameNumber(rawName: string): number | null {
  const clean = rawName.toUpperCase().replace(/[^А-ЯЁ]/g, '');
  if (clean.length < 2) return null;

  let sum = 0;
  for (const ch of clean) sum += LETTER_VALUES[ch] ?? 0;
  if (sum === 0) return null;

  // Мастер-числа 11 и 22 не сворачиваются.
  while (sum > 9 && sum !== 11 && sum !== 22) {
    sum = String(sum)
      .split('')
      .reduce((acc, d) => acc + Number(d), 0);
  }
  return sum;
}

